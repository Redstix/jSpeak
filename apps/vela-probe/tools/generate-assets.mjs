// Build stamp: UTC timestamp embedded into the page version header so a
// delivered RPK hash can be bound to an observable on-device identity.
// Format B<yyMMdd>T<HHmmss>, 14 chars; runs at least 1s apart differ.
function pad2(n) { return String(n).padStart(2, '0'); }
const now = new Date();
const stamp = 'B' + pad2(now.getUTCFullYear() % 100) + pad2(now.getUTCMonth() + 1) +
  pad2(now.getUTCDate()) + 'T' + pad2(now.getUTCHours()) + pad2(now.getUTCMinutes()) +
  pad2(now.getUTCSeconds());
if (!/^B\d{6}T\d{6}$/.test(stamp)) throw new Error('bad build stamp: ' + stamp);
writeFileSync(new URL('../src/build-stamp.js', import.meta.url),
  '// Generated by tools/generate-assets.mjs — do not edit; not committed to Git.\n' +
  "export var BUILD_STAMP = '" + stamp + "';\n");
console.log('Generated 64 KiB resource, bin.txt/big.txt probes, 512-byte ASCII text, 2s PCM16 WAV, icon, and build stamp ' + stamp);
