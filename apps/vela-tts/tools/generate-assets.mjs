import { mkdirSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const dir = new URL('../src/common/', import.meta.url);
mkdirSync(dir, { recursive: true });
function crc32(data) {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(name, data) {
  const type = Buffer.from(name), result = Buffer.alloc(12 + data.length);
  result.writeUInt32BE(data.length); type.copy(result, 4); data.copy(result, 8);
  result.writeUInt32BE(crc32(Buffer.concat([type, data])), 8 + data.length);
  return result;
}
const width = 64, pixels = Buffer.alloc((1 + width * 3) * width);
for (let y = 0; y < width; y++) for (let x = 0; x < width; x++) {
  const offset = y * (1 + width * 3) + 1 + x * 3;
  pixels[offset] = x > 20 && x < 44 && y > 12 && y < 52 ? 240 : 24;
  pixels[offset + 1] = x > 20 && x < 44 && y > 12 && y < 52 ? 240 : 48;
  pixels[offset + 2] = x > 20 && x < 44 && y > 12 && y < 52 ? 240 : 80;
}
const header = Buffer.alloc(13); header.writeUInt32BE(width); header.writeUInt32BE(width, 4);
header[8] = 8; header[9] = 2;
writeFileSync(new URL('logo.png', dir), Buffer.concat([
  Buffer.from('89504e470d0a1a0a', 'hex'), chunk('IHDR', header),
  chunk('IDAT', deflateSync(pixels)), chunk('IEND', Buffer.alloc(0)),
]));
function pad2(value) { return String(value).padStart(2, '0'); }
const now = new Date();
const stamp = 'B' + pad2(now.getUTCFullYear() % 100) + pad2(now.getUTCMonth() + 1) +
  pad2(now.getUTCDate()) + 'T' + pad2(now.getUTCHours()) + pad2(now.getUTCMinutes()) +
  pad2(now.getUTCSeconds());
if (!/^B\d{6}T\d{6}$/.test(stamp)) throw new Error('bad build stamp: ' + stamp);
writeFileSync(new URL('../src/build-stamp.js', import.meta.url),
  '// Generated by tools/generate-assets.mjs — do not edit; not committed to Git.\n' +
  "export var BUILD_STAMP = '" + stamp + "';\n");
console.log('Generated TTS icon and build stamp ' + stamp);
